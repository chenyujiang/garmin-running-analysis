"""Download the dashboard fonts once so the dashboard can serve them locally.

Fetches Noto Serif SC, Noto Sans SC and IBM Plex Sans as woff2 from Google
Fonts, split by unicode-range (the browser only loads the slices a page
uses), and writes them plus a rewritten `fonts.css` into
`src/running/dashboard/static/fonts/`. After this the dashboard makes no
requests outside the machine.

Run from analysis/:  uv run python scripts/fetch_fonts.py
"""

import re
import sys
import urllib.request
from pathlib import Path

CSS_URL = (
    "https://fonts.googleapis.com/css2"
    "?family=IBM+Plex+Sans:wght@400;500;600"
    "&family=Noto+Sans+SC:wght@400;500;700"
    "&family=Noto+Serif+SC:wght@600;900"
    "&display=swap"
)
# Google serves woff2 with unicode-range slices only to modern browsers.
USER_AGENT = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/130.0 Safari/537.36"
)
OUT = Path(__file__).resolve().parents[1] / "src" / "running" / "dashboard" / "static" / "fonts"


def get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def main() -> None:
    css = get(CSS_URL).decode("utf-8")
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.woff2"):
        old.unlink()
    out_css: list[str] = []
    n = 0
    for block in re.findall(r"@font-face\s*\{[^}]*\}", css):
        m = re.search(
            r"font-family: '([^']+)';.*?font-weight: (\d+);.*?url\((https://[^)]+)\)", block, re.S
        )
        if not m:
            continue
        family, weight, url = m.groups()
        n += 1
        name = f"{family.lower().replace(' ', '-')}-{weight}-{n:03d}.woff2"
        (OUT / name).write_bytes(get(url))
        out_css.append(block.replace(url, name))
    if any("https://" in b for b in out_css):
        raise SystemExit("fonts.css still references a remote URL")
    (OUT / "fonts.css").write_text(
        "/* Generated by analysis/scripts/fetch_fonts.py. Do not edit. */\n"
        + "\n".join(out_css)
        + "\n",
        encoding="utf-8",
    )
    size = sum(p.stat().st_size for p in OUT.glob("*.woff2"))
    print(f"{n} font files, {size / 1e6:.1f} MB in {OUT}")


if __name__ == "__main__":
    sys.exit(main())
